// Package gen emits typed Go stream functions from Canvas AST (canvas gen).
package gen

import (
	"fmt"
	"strconv"
	"strings"

	"github.com/zatrano/canvas/ast"
	"github.com/zatrano/canvas/rt"
)

// Emit generates a typed StreamXxx function by walking an AST-lowerable document.
// Supports Text, Echo ($path), and simple @foreach($items as $item) of map fields.
func Emit(pkg, funcName string, doc *ast.Document) (string, error) {
	if doc == nil || !doc.CanASTLower() {
		return "", fmt.Errorf("gen: document not AST-lowerable")
	}
	if _, ok, err := rt.CompileFunc(doc, "local"); err != nil || !ok {
		return "", fmt.Errorf("gen: compile failed: %w", err)
	}
	fields := map[string]bool{}
	itemFields := map[string]bool{}
	var itemAlias string
	collectFields(doc.Nodes, fields, itemFields, &itemAlias)

	var out strings.Builder
	out.WriteString("// Code generated by canvas gen. DO NOT EDIT.\n")
	out.WriteString("package " + pkg + "\n\n")
	out.WriteString("import \"github.com/zatrano/canvas/rt\"\n\n")
	if len(itemFields) > 0 {
		out.WriteString("type " + funcName + "Item struct {\n")
		for f := range itemFields {
			out.WriteString("\t" + exportIdent(f) + " string\n")
		}
		out.WriteString("}\n\n")
	}
	out.WriteString("// " + funcName + " is the typed stream for this Canvas template.\n")
	out.WriteString("func " + funcName + "(w *rt.Writer")
	for f := range fields {
		out.WriteString(", " + exportIdent(f) + " string")
	}
	if len(itemFields) > 0 {
		out.WriteString(", items []" + funcName + "Item")
	}
	out.WriteString(") {\n")
	if err := emitNodes(&out, doc.Nodes, fields, itemAlias, itemFields, "\t"); err != nil {
		return "", err
	}
	out.WriteString("}\n")
	return out.String(), nil
}

// EmitListPage is kept for the common list-page shape; prefer Emit for general templates.
func EmitListPage(pkg, funcName string, doc *ast.Document) (string, error) {
	return Emit(pkg, funcName, doc)
}

func collectFields(nodes []ast.Node, root, item map[string]bool, alias *string) {
	for _, n := range nodes {
		switch x := n.(type) {
		case ast.Echo:
			path := strings.TrimPrefix(strings.TrimSpace(x.Expr), "$")
			head, rest, hasDot := strings.Cut(path, ".")
			if *alias != "" && head == *alias && hasDot {
				item[rest] = true
			} else if !hasDot {
				root[head] = true
			} else if *alias == "" || head != *alias {
				root[head] = true
			}
		case ast.Block:
			if x.Name == "foreach" || x.Name == "forelse" {
				_, _, a, ok := parseForeachAlias(x.Args)
				if ok && *alias == "" {
					*alias = a
				}
			}
			if x.Name == "if" || x.Name == "unless" {
				collectCondFields(x.Args, root, item, *alias)
			}
			collectFields(x.Body, root, item, alias)
		}
	}
}

func parseForeachAlias(args string) (coll, key, alias string, ok bool) {
	// Reuse the same grammar as ast via a tiny local parse.
	args = strings.TrimSpace(args)
	const asSep = " as "
	i := strings.Index(strings.ToLower(args), asSep)
	if i < 0 {
		return "", "", "", false
	}
	left := strings.TrimSpace(args[:i])
	right := strings.TrimSpace(args[i+len(asSep):])
	coll = strings.TrimPrefix(left, "$")
	if arrow := strings.Index(right, "=>"); arrow >= 0 {
		k := strings.TrimSpace(right[:arrow])
		v := strings.TrimSpace(right[arrow+2:])
		return coll, strings.TrimPrefix(k, "$"), strings.TrimPrefix(v, "$"), true
	}
	return coll, "", strings.TrimPrefix(right, "$"), true
}

func emitNodes(b *strings.Builder, nodes []ast.Node, root map[string]bool, alias string, item map[string]bool, ind string) error {
	for _, n := range nodes {
		switch x := n.(type) {
		case ast.Text:
			if x.Value == "" {
				continue
			}
			b.WriteString(ind)
			b.WriteString("w.WriteString(")
			b.WriteString(strconv.Quote(x.Value))
			b.WriteString(")\n")
		case ast.Echo:
			path := strings.TrimPrefix(strings.TrimSpace(x.Expr), "$")
			head, rest, hasDot := strings.Cut(path, ".")
			b.WriteString(ind)
			b.WriteString("rt.WriteEscaped(w, ")
			if alias != "" && head == alias && hasDot {
				b.WriteString("it." + exportIdent(rest))
			} else if !hasDot {
				b.WriteString(exportIdent(head))
			} else {
				return fmt.Errorf("gen: unsupported echo $%s", path)
			}
			b.WriteString(")\n")
		case ast.Block:
			switch x.Name {
			case "foreach", "forelse":
				_, _, a, ok := parseForeachAlias(x.Args)
				if !ok {
					return fmt.Errorf("gen: bad foreach")
				}
				body := x.Body
				if x.Name == "forelse" {
					// skip @empty marker branch for typed emit of the loop body only
					for i, n := range body {
						if d, ok := n.(ast.Directive); ok && d.Name == "empty" && strings.TrimSpace(d.Args) == "" {
							body = body[:i]
							break
						}
					}
				}
				b.WriteString(ind + "for i := 0; i < len(items); i++ {\n")
				b.WriteString(ind + "\tit := items[i]\n")
				_ = a
				if err := emitNodes(b, body, root, alias, item, ind+"\t"); err != nil {
					return err
				}
				b.WriteString(ind + "}\n")
			case "if", "unless":
				cond, ok := rt.ParseCond(strings.TrimSpace(x.Args))
				if !ok {
					return fmt.Errorf("gen: bad %s condition %q", x.Name, x.Args)
				}
				expr, err := emitCondExpr(cond, root, alias, item)
				if err != nil {
					return err
				}
				if x.Name == "unless" {
					expr = "!(" + expr + ")"
				}
				main, elseBody := splitGenElse(x.Body)
				b.WriteString(ind + "if " + expr + " {\n")
				if err := emitNodes(b, main, root, alias, item, ind+"\t"); err != nil {
					return err
				}
				if len(elseBody) > 0 {
					b.WriteString(ind + "} else {\n")
					if err := emitNodes(b, elseBody, root, alias, item, ind+"\t"); err != nil {
						return err
					}
				}
				b.WriteString(ind + "}\n")
			default:
				if err := emitNodes(b, x.Body, root, alias, item, ind); err != nil {
					return err
				}
			}
		case ast.Comment, ast.Directive:
			continue
		default:
			return fmt.Errorf("gen: unsupported node %T", n)
		}
	}
	return nil
}

func exportIdent(s string) string {
	s = strings.ReplaceAll(s, ".", "_")
	if s == "" {
		return "X"
	}
	r := []rune(s)
	if r[0] >= 'a' && r[0] <= 'z' {
		r[0] = r[0] - ('a' - 'A')
	}
	return string(r)
}

func splitGenElse(body []ast.Node) (main, elseBody []ast.Node) {
	for i, n := range body {
		if d, ok := n.(ast.Directive); ok && d.Name == "else" && strings.TrimSpace(d.Args) == "" {
			return body[:i], body[i+1:]
		}
	}
	return body, nil
}

func collectCondFields(args string, root, item map[string]bool, alias string) {
	cond, ok := rt.ParseCond(strings.TrimSpace(args))
	if !ok {
		return
	}
	walkCondFields(cond, root, item, alias)
}

func walkCondFields(c rt.Cond, root, item map[string]bool, alias string) {
	for _, sub := range c.And {
		walkCondFields(sub, root, item, alias)
	}
	for _, sub := range c.Or {
		walkCondFields(sub, root, item, alias)
	}
	markPath := func(path []string) {
		if len(path) == 0 {
			return
		}
		if alias != "" && path[0] == alias {
			if len(path) > 1 {
				item[strings.Join(path[1:], ".")] = true
			}
			return
		}
		root[path[0]] = true
	}
	markPath(c.Truthy)
	markPath(c.Left)
	markPath(c.RightPath)
}

func emitCondExpr(c rt.Cond, root map[string]bool, alias string, item map[string]bool) (string, error) {
	if len(c.Or) > 0 {
		parts := make([]string, 0, len(c.Or))
		for _, sub := range c.Or {
			p, err := emitCondExpr(sub, root, alias, item)
			if err != nil {
				return "", err
			}
			parts = append(parts, "("+p+")")
		}
		return strings.Join(parts, " || "), nil
	}
	if len(c.And) > 0 {
		parts := make([]string, 0, len(c.And))
		for _, sub := range c.And {
			p, err := emitCondExpr(sub, root, alias, item)
			if err != nil {
				return "", err
			}
			parts = append(parts, "("+p+")")
		}
		return strings.Join(parts, " && "), nil
	}
	if c.Op != "" {
		left, err := emitPathValue(c.Left, root, alias, item)
		if err != nil {
			return "", err
		}
		if c.HasLit {
			return fmt.Sprintf("%s %s %s", left, c.Op, litGo(c.RightLit)), nil
		}
		right, err := emitPathValue(c.RightPath, root, alias, item)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s %s %s", left, c.Op, right), nil
	}
	if len(c.Truthy) > 0 {
		v, err := emitPathValue(c.Truthy, root, alias, item)
		if err != nil {
			return "", err
		}
		return v + ` != ""`, nil
	}
	return "", fmt.Errorf("gen: empty condition")
}

func emitPathValue(path []string, root map[string]bool, alias string, item map[string]bool) (string, error) {
	if len(path) == 0 {
		return "", fmt.Errorf("gen: empty path")
	}
	if alias != "" && path[0] == alias {
		if len(path) == 1 {
			return "it", nil
		}
		return "it." + exportIdent(strings.Join(path[1:], ".")), nil
	}
	if len(path) > 1 {
		// Typed emit only supports root scalars and item fields.
		return "", fmt.Errorf("gen: nested root path $%s not supported in typed emit", strings.Join(path, "."))
	}
	_ = root
	_ = item
	return exportIdent(path[0]), nil
}

func litGo(v any) string {
	switch t := v.(type) {
	case string:
		return strconv.Quote(t)
	case bool:
		if t {
			return "true"
		}
		return "false"
	case int:
		return strconv.Itoa(t)
	case float64:
		return strconv.FormatFloat(t, 'g', -1, 64)
	default:
		return strconv.Quote(fmt.Sprint(v))
	}
}

