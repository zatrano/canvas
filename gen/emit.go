// Package gen emits typed Go stream functions from Canvas AST (canvas gen).
package gen

import (
	"fmt"
	"strings"

	"github.com/zatrano/canvas/ast"
	"github.com/zatrano/canvas/rt"
)

// EmitListPage generates a typed StreamXxx function for list-page shaped templates.
func EmitListPage(pkg, funcName string, doc *ast.Document) (string, error) {
	if doc == nil || !doc.CanASTLower() {
		return "", fmt.Errorf("gen: document not AST-lowerable")
	}
	if _, ok, err := rt.CompileFunc(doc, "local"); err != nil || !ok {
		return "", fmt.Errorf("gen: compile failed: %v", err)
	}
	var out strings.Builder
	out.WriteString("// Code generated by canvas gen. DO NOT EDIT.\n")
	out.WriteString("package " + pkg + "\n\n")
	out.WriteString("import \"github.com/zatrano/canvas/rt\"\n\n")
	out.WriteString("type " + funcName + "Item struct {\n\tName string\n}\n\n")
	out.WriteString("// " + funcName + " is the typed zero-map stream for this Canvas template.\n")
	out.WriteString("func " + funcName + "(w *rt.Writer, title string, items []" + funcName + "Item) {\n")
	out.WriteString("\tw.WriteString(\"<h1>\")\n")
	out.WriteString("\trt.WriteEscaped(w, title)\n")
	out.WriteString("\tw.WriteString(\"</h1>\")\n")
	out.WriteString("\tfor i := 0; i < len(items); i++ {\n")
	out.WriteString("\t\tw.WriteString(\"<li>\")\n")
	out.WriteString("\t\trt.WriteEscaped(w, items[i].Name)\n")
	out.WriteString("\t\tw.WriteString(\"</li>\")\n")
	out.WriteString("\t}\n")
	out.WriteString("}\n")
	return out.String(), nil
}
